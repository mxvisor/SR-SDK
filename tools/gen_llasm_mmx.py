"""Writes SR/SR/llasm-support/llasm_mmx.llinc from the MMX_OPS list of llasm_mmx.c:
the funcs of the helpers and an MMX_<NAME> constant per operation.  Run it after
the list changes (it needs no arguments, and checks the file with --check)."""
import os
import re
import sys

DIR = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'SR', 'SR', 'llasm-support')
source = open(os.path.join(DIR, 'llasm_mmx.c')).read()
block = re.search(r'#define MMX_OPS\(X\)(.*?)\n\n', source, re.S).group(1)
names = re.findall(r'X\((\w+)\)', block)

lines = [
    ';part of static recompiler -- do not edit', '',
    ';; Generated by SR-SDK/tools/gen_llasm_mmx.py from llasm_mmx.c.', ';;', '',
    'funcv x86_mmx_rr $, op, dst, src',
    'funcv x86_mmx_rm $, op, dst, *src',
    'funcv x86_mmx_ri $, op, dst, imm',
    'funcv x86_mmx_movd_in $, dst, value',
    'funcv x86_mmx_movd_load $, dst, *src',
    'func x86_mmx_movd_out $, src',
    'funcv x86_mmx_movd_store $, src, *dst',
    'funcv x86_mmx_movq_store $, src, *dst',
    'funcv x86_mmx_pshufw_rr $, dst, src, imm',
    'funcv x86_mmx_pshufw_rm $, dst, *src, imm',
    'func x86_mmx_pextrw $, src, imm',
    'funcv x86_mmx_pinsrw $, dst, value, imm',
    'func x86_mmx_pmovmskb $, src',
    'funcv x86_mmx_maskmovq $, data, mask, *dst', '',
]
lines += ['define MMX_%s %d' % (name, index) for index, name in enumerate(names)]
text = '\n'.join(lines) + '\n'
path = os.path.join(DIR, 'llasm_mmx.llinc')
if '--check' in sys.argv:
    sys.exit(0 if os.path.exists(path) and open(path).read() == text else 'llasm_mmx.llinc is out of date')
open(path, 'w').write(text)
